"""Fill T07.md section 4 from analysis.log, verbatim, so no number in the write-up is typed (AGENT.md rule 4).

    python tests/T07/fill_writeup.py                         # after analyse.py
    python tests/T07/fill_writeup.py --doc COPY.md --log analysis.log     # on a copy (how this script is tested)

Replaces everything between the section-4 markers (or, the first time, the placeholder under the heading line '## 4. Results').
Sections 1-3 are never touched. This script has failed that promise twice in T03 (F-AA-M02), so it proves it:
  * '## 4. Results' is located only as a whole line (the header of T07.md mentions it inside backticks);
  * the frozen region is hashed exactly as check_prereg.py hashes it (from the line '## 1. Idea and references' to the line
    '## 4. Results', LF endings, trailing whitespace stripped) before and after, and the file is written only if the two hashes are
    equal and the bytes in front of the section-4 heading are identical;
  * check_prereg.py is run straight after by run.sh.
Files are read and written as bytes with their own line endings; nothing is re-encoded.
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BEGIN = "<!-- §4 BEGIN (generated by fill_writeup.py from analysis.log; do not edit) -->"
END = "<!-- §4 END -->"
TITLES = {"4.0a": "4.0a The worked example: one real event and one N4.6 draw", "4.0b": "4.0b Gates V1-V7, the nulls' tables and reportability", "4.1": "4.1 Headline: both nulls and the whole-book switch",
          "4.2": "4.2 Comparators, weight by band, trades", "4.3": "4.3 Power, the minimum detectable edge, calibration and the null spreads", "4.4": "4.4 Verdict against each pre-registered criterion",
          "4.5": "4.5 Robustness R1-R6"}
ORDER = ["4.0a", "4.0b", "4.1", "4.2", "4.3", "4.4", "4.5"]
H1 = re.compile(r"^## 1\. Idea and references[ \t\r]*$", re.M)  # [\r]: T07.md has CRLF line endings
H4 = re.compile(r"^## 4\. Results[ \t\r]*$", re.M)
H5 = re.compile(r"^## 5\. Findings[ \t\r]*$", re.M)


def frozen_hash(text: str) -> str:
    """The hash check_prereg.py computes: from the section 1 heading line up to (not including) the section 4 heading line."""
    a = H1.search(text).start()
    b = H4.search(text).start()
    reg = "\n".join(l.rstrip() for l in text[a:b].replace("\r\n", "\n").split("\n"))
    return hashlib.sha256(reg.encode("utf-8")).hexdigest()


def blocks(log_lines):
    pre, out, name = [], {}, None
    for l in log_lines:
        if l.strip() and set(l.strip()) <= {"="}:
            continue
        m = re.match(r"^(4\.\d[ab]?)  ", l)  # the heading lines of analyse.py have two spaces after the id
        if m and m.group(1) in TITLES:
            name = m.group(1)
            out[name] = []
            continue
        (out[name] if name else pre).append(l)
    return pre, out


def fence(lines):
    lines = list(lines)
    while lines and not lines[-1].strip():
        lines = lines[:-1]
    while lines and not lines[0].strip():
        lines = lines[1:]
    return ["```text", *lines, "```", ""]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--doc", default=str(HERE / "T07.md"))
    ap.add_argument("--log", default=str(HERE / "analysis.log"))
    a = ap.parse_args()
    doc, log = Path(a.doc), Path(a.log)
    raw = doc.read_bytes()
    nl = "\r\n" if b"\r\n" in raw else "\n"
    t = raw.decode("utf-8")
    pre, b = blocks(log.read_text(encoding="utf-8").splitlines())
    missing = [k for k in ORDER if k not in b]
    if missing:
        print("analysis.log lacks the blocks", missing, ": refusing to write")
        return 1
    body = [BEGIN, "", "Every table below is printed by `analyse.py`; the full output is `analysis.log`. Nothing here is typed.", "", *fence(pre)]
    for k in ORDER:
        body += [f"### {TITLES[k]}", "", *fence(b[k])]
    body += [END]
    new_block = nl.join(body)

    if not (H1.search(t) and H4.search(t) and H5.search(t)):
        print("could not find the section 1, 4 and 5 heading lines: refusing to write")
        return 1
    before = frozen_hash(t)
    if BEGIN in t:
        if t.count(BEGIN) != 1 or t.count(END) != 1 or t.index(END) < t.index(BEGIN) or t.index(BEGIN) < H4.search(t).start():
            print("section-4 markers are missing, duplicated or misplaced: refusing to write")
            return 1
        i, j = t.index(BEGIN), t.index(END) + len(END)
        new = t[:i] + new_block + t[j:]
    else:
        h4, h5 = H4.search(t), H5.search(t)
        new = t[:h4.start()] + "## 4. Results" + nl + nl + new_block + nl + nl + t[h5.start():]
    cut = H4.search(t).start()
    if frozen_hash(new) != before or new[:cut] != t[:cut] or new.encode("utf-8")[:len(t[:cut].encode("utf-8"))] != t[:cut].encode("utf-8"):
        print("sections 1-3 would change: refusing to write")
        return 1
    # sections 5-8 must survive too
    tail_old, tail_new = t[H5.search(t).start():], new[H5.search(new).start():]
    if tail_old != tail_new:
        print("sections 5-8 would change: refusing to write")
        return 1
    doc.write_bytes(new.encode("utf-8"))
    print(f"filled section 4 of {doc.name} from {log.name}; sections 1-3 and 5-8 unchanged (frozen hash {before[:16]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
