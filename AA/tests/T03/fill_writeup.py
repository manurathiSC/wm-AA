"""Fill T03.md section 4 from analysis.log, verbatim, so no number in the write-up is typed (AGENT.md rule 4).

    python fill_writeup.py        # after analyse.py

Replaces everything between the section-4 markers (or, the first time, the placeholder under '## 4. Results').
Sections 1-3 are never touched; `check_prereg.py` confirms their hash is unchanged.
"""
import hashlib
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
LOG = (HERE / "analysis.log").read_text(encoding="utf-8").splitlines()
DOC = HERE / "T03.md"
BEGIN = "<!-- §4 BEGIN (generated by fill_writeup.py from analysis.log; do not edit) -->"
END = "<!-- §4 END -->"
TITLES = {"4.0a": "4.0a The worked example", "4.0b": "4.0b Gates, the null check and reportability", "4.1": "4.1 Headline",
          "4.2": "4.2 Comparators", "4.3": "4.3 Power and the minimum detectable edge", "4.4": "4.4 Verdict against each pre-registered criterion"}


def blocks():
    pre, cur, out, name = [], None, {}, None
    for l in LOG:
        if set(l.strip()) <= {"="} and l.strip():
            continue
        m = re.match(r"^(4\.\d[ab]?)\s", l)
        if m and m.group(1) in TITLES:
            name = m.group(1)
            out[name] = []
            continue
        (out[name] if name else pre).append(l)
    return pre, out


def fence(lines):
    while lines and not lines[-1].strip():
        lines = lines[:-1]
    while lines and not lines[0].strip():
        lines = lines[1:]
    return ["```text", *lines, "```", ""]


def main():
    pre, b = blocks()
    body = [BEGIN, "", "Every table below is printed by `analyse.py`; the full output is `analysis.log`. Nothing here is typed.", "", *fence(pre)]
    for k in ("4.0a", "4.0b", "4.1", "4.2", "4.3", "4.4"):
        body += [f"### {TITLES[k]}", "", *fence(b[k])]
    body += [END]
    t = DOC.read_text(encoding="utf-8")

    def frozen(x):  # the pre-registered text: from the section 1 heading line to the section 4 heading line
        return hashlib.sha256(x[x.index("\n## 1. Idea and references"):x.index("\n## 4. Results\n")].encode()).hexdigest()

    before = frozen(t)
    if BEGIN in t:
        i, j = t.index(BEGIN), t.index(END) + len(END)
        t = t[:i] + "\n".join(body) + t[j:]
    else:
        # anchor on the heading LINE: the header also mentions "## 4. Results" inside backticks
        i = t.index("\n## 4. Results\n") + 1
        j = t.index("\n## 5. Findings\n") + 1
        t = t[:i] + "## 4. Results\n\n" + "\n".join(body) + "\n\n" + t[j:]
    assert frozen(t) == before, "sections 1-3 would change: refusing to write"
    DOC.write_text(t, encoding="utf-8")
    print("filled section 4 from analysis.log")


if __name__ == "__main__":
    main()
