"""Copy analysis.log into T04.md section 4 (between the BEGIN and END markers). Sections 1-3 must stay byte-identical (F-AA-M02):
the file is rewritten only if the frozen hash is unchanged before and after, and it is written through a temporary file.

    python tests/T04/fill_writeup.py            (from AA/)
"""
import hashlib
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
F = HERE / "T04.md"
BEGIN = "<!-- §4 BEGIN (generated by fill_writeup.py from analysis.log; do not edit) -->"
END = "<!-- §4 END -->"


def frozen_region(text: str) -> str:
    a = text.index("\n## 1. Idea and references") + 1
    b = text.index("\n## 4. Results") + 1
    return "\n".join(l.rstrip() for l in text[a:b].replace("\r\n", "\n").split("\n"))


def main() -> int:
    t = F.read_text(encoding="utf-8")
    h0 = hashlib.sha256(frozen_region(t).encode("utf-8")).hexdigest()
    recorded = re.search(r"\*\*§1–§3 sha256:\*\* `([^`]*)`", t).group(1)
    if h0 != recorded:
        print("sections 1-3 do not match the recorded hash; not writing"); return 1
    log = (HERE / "analysis.log").read_text(encoding="utf-8")
    log = re.sub(r"^# .*\n\n?", "", log, count=1)
    log = re.sub(r"^###", "####", log, flags=re.M)
    log = re.sub(r"^## ", "### ", log, flags=re.M)
    a, b = t.index(BEGIN), t.index(END)
    new = t[: a + len(BEGIN)] + "\n\nEvery table below is printed by `analyse.py`; the full output is `analysis.log`. Nothing here is typed.\n\n" + log.strip() + "\n\n" + t[b:]
    h1 = hashlib.sha256(frozen_region(new).encode("utf-8")).hexdigest()
    if h1 != recorded:
        print("the new text would change sections 1-3; not writing"); return 2
    tmp = F.with_suffix(".md.tmp")
    tmp.write_text(new, encoding="utf-8")
    tmp.replace(F)
    print("section 4 written; sections 1-3 hash unchanged", h1)
    return 0


if __name__ == "__main__":
    sys.exit(main())
