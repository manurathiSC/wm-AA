"""Fill T10.md section 4 from analysis.log, verbatim, so no number in the write-up is typed (AGENT.md rule 4).

    python -I tests/T10/fill_writeup.py [--run headline]                      after analyse.py (reads evidence/<run>/analysis.log)
    python -I tests/T10/fill_writeup.py --doc COPY.md --log analysis.log      on a copy (how this script is tested)

Replaces everything between the section-4 markers (or, the first time, the placeholder under the heading line '## 4. Results').
Sections 1-3 are never touched. This promise was broken twice in T03 (F-AA-M02), so the script proves it:
  * '## 1. Idea and references' and '## 4. Results' are located only as whole lines (the header of T10.md mentions them inside backticks);
  * the frozen region is hashed with check_prereg.py's own `region()` function, before and after, and compared with the sha256 in the header;
    the file is written only if the two hashes are equal (and equal to the header's sha256) and the bytes in front of the section-4 heading
    and everything from '## 5. Findings' on are identical;
  * after writing, the file is read back and the same checks are repeated (the original bytes are restored if they fail); check_prereg.py is
    run straight after by run.sh.
Files are read and written as bytes with their own line endings; nothing is re-encoded. Sections 5-8 are never filled by this script.
"""
import argparse
import hashlib
import importlib.util
import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
BEGIN = "<!-- §4 BEGIN (generated by fill_writeup.py from analysis.log; do not edit) -->"
END = "<!-- §4 END -->"
TITLES = {"4.0a": "4.0a The worked example: one real weekly decision, from the basket to the trade and the NAV",
          "4.0b": "4.0b Gates V1-V5, consistency checks and reportability",
          "4.1": "4.1 Headline: C1-C4 per book and the 3-of-4 verdict (no chance benchmark was run)",
          "4.2": "4.2 Bootstrap intervals, per-year returns and trades",
          "4.3": "4.3 The extra weeks: stretch table (R7), signal patterns and FS",
          "4.4": "4.4 Verdict against each pre-registered criterion and the outcome map",
          "4.5": "4.5 Robustness and descriptive checks R1-R8"}
ORDER = ["4.0a", "4.0b", "4.1", "4.2", "4.3", "4.4", "4.5"]
H1 = re.compile(r"^## 1\. Idea and references[ \t\r]*$", re.M)
H4 = re.compile(r"^## 4\. Results[ \t\r]*$", re.M)
H5 = re.compile(r"^## 5\. Findings[ \t\r]*$", re.M)
HDR = re.compile(r"^\*\*§1–§3 sha256:\*\* `([^`]*)`", re.M)


def load_region():
    """check_prereg.py's own region() (loaded from its file, so the two cannot drift apart)."""
    spec = importlib.util.spec_from_file_location("t10_check_prereg", HERE / "check_prereg.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.region


def frozen_hash(text: str, region) -> str:
    return hashlib.sha256(region(text).encode("utf-8")).hexdigest()


def blocks(log_lines):
    pre, out, name = [], {}, None
    for l in log_lines:
        if l.strip() and set(l.strip()) <= {"="}:
            continue
        m = re.match(r"^(4\.\d[ab]?)  ", l)  # the heading lines of analyse.py have two spaces after the id
        if m and m.group(1) in TITLES:
            name = m.group(1)
            out[name] = []
            continue
        (out[name] if name else pre).append(l)
    return pre, out


def fence(lines):
    lines = list(lines)
    while lines and not lines[-1].strip():
        lines = lines[:-1]
    while lines and not lines[0].strip():
        lines = lines[1:]
    return ["```text", *lines, "```", ""]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--doc", default=str(HERE / "T10.md"))
    ap.add_argument("--run", default="headline")
    ap.add_argument("--log", default=None, help="default evidence/<run>/analysis.log")
    a = ap.parse_args()
    doc = Path(a.doc)
    log = Path(a.log) if a.log else HERE / "evidence" / a.run / "analysis.log"
    region = load_region()
    raw = doc.read_bytes()
    nl = "\r\n" if b"\r\n" in raw else "\n"
    t = raw.decode("utf-8")
    logtxt = log.read_text(encoding="utf-8")
    pre, b = blocks(logtxt.splitlines())
    missing = [k for k in ORDER if k not in b]
    if missing:
        print("analysis.log lacks the blocks", missing, ": refusing to write")
        return 1
    if "FAILED: nothing below may be read" in logtxt:
        print("analysis.log reports a failed gate: refusing to write")
        return 1
    body = [BEGIN, "", "Every table below is printed by `analyse.py` from the evidence; the full output is `evidence/<run>/analysis.log`. Nothing here is typed. "
            "**No null was run: no chance benchmark exists for any number below.**", "", *fence(pre)]
    for k in ORDER:
        body += [f"### {TITLES[k]}", "", *fence(b[k])]
    body += [END]
    new_block = nl.join(body)

    if not (H1.search(t) and H4.search(t) and H5.search(t)):
        print("could not find the section 1, 4 and 5 heading lines: refusing to write")
        return 1
    before = frozen_hash(t, region)
    hdr = HDR.search(t)
    if hdr is None or hdr.group(1) != before:
        print(f"the frozen region of {doc.name} does not match its header sha256 ({hdr.group(1)[:16] if hdr else 'no header line'} vs {before[:16]}): refusing to write")
        return 1
    if BEGIN in t:
        if t.count(BEGIN) != 1 or t.count(END) != 1 or t.index(END) < t.index(BEGIN) or t.index(BEGIN) < H4.search(t).start():
            print("section-4 markers are missing, duplicated or misplaced: refusing to write")
            return 1
        i, j = t.index(BEGIN), t.index(END) + len(END)
        new = t[:i] + new_block + t[j:]
    else:
        h4, h5 = H4.search(t), H5.search(t)
        new = t[:h4.start()] + "## 4. Results" + nl + nl + new_block + nl + nl + t[h5.start():]
    cut = H4.search(t).start()
    if frozen_hash(new, region) != before or new[:cut] != t[:cut] or new.encode("utf-8")[:len(t[:cut].encode("utf-8"))] != t[:cut].encode("utf-8"):
        print("sections 1-3 would change: refusing to write")
        return 1
    if t[H5.search(t).start():] != new[H5.search(new).start():]:
        print("sections 5-8 would change: refusing to write")
        return 1
    doc.write_bytes(new.encode("utf-8"))
    # read back and prove it again
    back = doc.read_bytes().decode("utf-8")
    hdr2 = HDR.search(back)
    ok = (frozen_hash(back, region) == before and back[:cut] == t[:cut] and back[H5.search(back).start():] == t[H5.search(t).start():]
          and back.count(BEGIN) == 1 and back.count(END) == 1 and hdr2 is not None and hdr2.group(1) == before)
    if not ok:
        doc.write_bytes(raw)
        print("read-back check failed: the original bytes were restored")
        return 1
    print(f"filled section 4 of {doc.name} from {log}; sections 1-3 (frozen hash {before[:16]}) and 5-8 unchanged; read-back verified")
    return 0


if __name__ == "__main__":
    sys.exit(main())
