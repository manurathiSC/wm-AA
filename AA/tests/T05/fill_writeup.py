"""Copy analysis.log into T05.md section 4 (between the BEGIN and END markers). Sections 1-3 must stay byte-identical (F-AA-M02):
the file is rewritten only if the frozen hash is unchanged before and after AND the raw bytes of sections 1-3 are unchanged,
and it is written through a temporary file. The file's own line endings (CRLF or LF) are kept.

    python tests/T05/fill_writeup.py [--root DIR]            (from AA/)

--root (default: this folder) is where T05.md and analysis.log are read; it exists to exercise the script on a scratch copy.
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BEGIN = "<!-- §4 BEGIN (generated by fill_writeup.py from analysis.log; do not edit) -->"
END = "<!-- §4 END -->"


def span(text: str) -> tuple[int, int]:
    return text.index("\n## 1. Idea and references") + 1, text.index("\n## 4. Results") + 1


def frozen_region(text: str) -> str:
    a, b = span(text)
    return "\n".join(l.rstrip() for l in text[a:b].replace("\r\n", "\n").split("\n"))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(HERE))
    root = Path(ap.parse_args().root)
    F = root / "T05.md"
    t = F.read_bytes().decode("utf-8")                     # raw: line endings untouched
    eol = "\r\n" if "\r\n" in t else "\n"
    h0 = hashlib.sha256(frozen_region(t).encode("utf-8")).hexdigest()
    recorded = re.search(r"\*\*§1–§3 sha256:\*\* `([^`]*)`", t).group(1)
    if h0 != recorded:
        print("sections 1-3 do not match the recorded hash; not writing"); return 1
    log = (root / "analysis.log").read_text(encoding="utf-8")
    log = re.sub(r"^# .*\n\n?", "", log, count=1)
    log = re.sub(r"^###", "####", log, flags=re.M)
    log = re.sub(r"^## ", "### ", log, flags=re.M)
    a, b = t.index(BEGIN), t.index(END)
    body = "\n\nEvery table below is printed by `analyse.py`; the full output is `analysis.log`. Nothing here is typed.\n\n" + log.strip() + "\n\n"
    new = t[: a + len(BEGIN)] + body.replace("\n", eol) + t[b:]
    h1 = hashlib.sha256(frozen_region(new).encode("utf-8")).hexdigest()
    if h1 != recorded:
        print("the new text would change sections 1-3; not writing"); return 2
    a0, b0 = span(t)
    a1, b1 = span(new)
    if t[:a0] != new[:a1] or t[a0:b0] != new[a1:b1]:
        print("the header or sections 1-3 are not byte-identical after the edit; not writing"); return 3
    tmp = F.with_suffix(".md.tmp")
    tmp.write_bytes(new.encode("utf-8"))
    tmp.replace(F)
    print("section 4 written; sections 1-3 hash unchanged", h1)
    return 0


if __name__ == "__main__":
    sys.exit(main())
