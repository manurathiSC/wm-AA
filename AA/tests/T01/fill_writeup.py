"""
Fill T01.md §4 from analysis.log, verbatim, so no number in the write-up is typed
(AGENT.md rule 4). Blocks are located by their headers in analysis.log, never by line
number. Re-run after analyse.py; it replaces everything between the §4 markers.

    python AA/tests/T01/fill_writeup.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
LOG = (HERE / "analysis.log").read_text(encoding="utf-8").splitlines()
DOC = HERE / "T01.md"
BEGIN, END = "<!-- §4 BEGIN (generated by fill_writeup.py from analysis.log; do not edit) -->", "<!-- §4 END -->"


def block(start: str, stop: str | None, skip_rules: bool = True) -> list[str]:
    """Lines from the first line containing `start` up to (not including) the first later line containing `stop`."""
    i = next(k for k, l in enumerate(LOG) if start in l)
    j = next((k for k in range(i + 1, len(LOG)) if stop and stop in LOG[k]), len(LOG))
    out = [l for l in LOG[i:j] if not (skip_rules and set(l.strip()) <= {"="})]
    while out and not out[-1].strip():
        out.pop()
    return out


def fence(lines: list[str]) -> list[str]:
    """Plain console lines go in a text fence; markdown tables pass through."""
    res, buf = [], []
    for l in lines:
        if l.startswith("|"):
            if buf:
                res += ["```text", *buf, "```"]
                buf = []
            res.append(l)
        else:
            if res and res[-1].startswith("|") and l.strip() == "":
                res.append("")
                continue
            buf.append(l)
    if buf:
        res += ["```text", *buf, "```"]
    return res


parts = [
    BEGIN,
    "",
    "Every table below is printed by `analyse.py` and copied verbatim from `analysis.log` by `fill_writeup.py`. "
    "The full output, including every config × book × window of the sweep, is in `analysis.log`.",
    "",
    "### 4.0 Gates and the null check",
    "",
    *fence(block("4.0 VALIDITY GATES", "Schema and cross-layer identity")),
    "",
    *fence(block("4.0b NULL CHECK MEASURED", "--- run cash_sleeve")),
    "",
    "### 4.1 Headline: R = `pct_w65_q25` (weekly), 50/50 sleeve",
    "",
    *fence(block("--- headline: return against the null", "REPORTABILITY GATE")),
    "",
    "### 4.2 Reportability",
    "",
    *fence(block("REPORTABILITY GATE", "VERDICTS")),
    "",
    "### 4.3 Verdicts against the pre-registered criteria",
    "",
    *fence(block("VERDICTS — pre-registered criteria", "ROBUSTNESS")),
    "",
    "### 4.4 Robustness (pre-registered; decides status, not verdicts)",
    "",
    *fence(block("ROBUSTNESS — pre-registered", "--- R4 cash_sleeve run, R: return against the null")),
    "",
    "### 4.5 Verdict per hypothesis",
    "",
    *fence(block("HYPOTHESES (R, after cost", "MULTIPLICITY")),
    "",
    "### 4.6 Multiplicity: the best of the sweep against the null of best rows",
    "",
    *fence(block("MULTIPLICITY — best of", "DESCRIPTIVE SWEEP")),
    "",
    "### 4.7 Descriptive sweep summary (no claims)",
    "",
    *fence(block("--- Sweep summary across books", "--- Distinct realisations")),
    "",
    *fence(block("--- Distinct realisations", "PER-YEAR RETURNS")),
    "",
    "Per-config, per-book tables and per-year returns for R are in `analysis.log` (sections DESCRIPTIVE SWEEP and PER-YEAR RETURNS).",
    "",
    END,
]
text = DOC.read_text(encoding="utf-8")
a, b = text.index(BEGIN), text.index(END) + len(END)
DOC.write_text(text[:a] + "\n".join(parts) + text[b:], encoding="utf-8")
print("§4 filled:", sum(1 for p in parts if p.startswith("|")), "table rows")
